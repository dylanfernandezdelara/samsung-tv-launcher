// Turn the images in wallpapers-src/ into TV-sized JPEGs in launcher/wallpapers/ plus a list the
// launcher reads. Drop any landscape images into wallpapers-src/ first (it's gitignored).
// Example: the 1984 Macintosh wallpapers from https://basicappleguy.com/haberdashery/macintoshwallpapers
// Resizing uses `sips` (macOS) or `ffmpeg` if installed.  Usage: npm run wallpapers
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const ROOT = path.join(__dirname, '..');
const SRC = path.join(ROOT, 'wallpapers-src');
const OUT = path.join(ROOT, 'launcher', 'wallpapers');

const has = (cmd) => { try { execFileSync('which', [cmd], { stdio: 'ignore' }); return true; } catch (e) { return false; } };
const tool = has('sips') ? 'sips' : has('ffmpeg') ? 'ffmpeg' : null;

const files = fs.existsSync(SRC) ? fs.readdirSync(SRC).filter((f) => /\.(png|jpe?g|heic|webp)$/i.test(f)).sort() : [];
if (!files.length) {
  console.log('No images in wallpapers-src/. Add some, then run this again. (Without any, the launcher uses built-in gradients.)');
  process.exit(0);
}
if (!tool) { console.log('Need `sips` (macOS) or `ffmpeg` to resize. Install ffmpeg and retry.'); process.exit(1); }

fs.rmSync(OUT, { recursive: true, force: true });   // launcher/wallpapers/ is fully regenerated
fs.mkdirSync(OUT, { recursive: true });
const list = [];
for (const f of files) {
  const name = path.basename(f, path.extname(f)).toLowerCase().replace(/[^a-z0-9]+/g, '-') + '.jpg';
  const out = path.join(OUT, name);
  if (tool === 'sips') execFileSync('sips', ['-s', 'format', 'jpeg', '-s', 'formatOptions', '82', '--resampleWidth', '1920', path.join(SRC, f), '--out', out], { stdio: 'ignore' });
  else execFileSync('ffmpeg', ['-loglevel', 'error', '-y', '-i', path.join(SRC, f), '-vf', 'scale=1920:-2', '-q:v', '3', out]);
  list.push('wallpapers/' + name);
  console.log('  ' + name);
}
fs.writeFileSync(path.join(OUT, 'list.js'), '// generated by npm run wallpapers\nvar LAUNCHER_WALLPAPERS = ' + JSON.stringify(list, null, 2) + ';\n');
console.log(`${list.length} wallpapers ready. Run npm run deploy to put them on the TV.`);
